#!/usr/bin/env python
r"""
gen_tier_sets.py - write tier_sets_data.py from the tier-color research.

    python scripts\gen_tier_sets.py            # rewrite tier_sets_data.py
    python scripts\gen_tier_sets.py --check    # fail if it is out of date

WHY
---
The ten tier-color sets - two for normal vision and one for each of eight
kinds of color blindness - come from Loyd's research at
`D:\Facetdiagrams.org\research\tier-colors` ("Tier Colors and Color Blindness
v1.01.pdf" describes every one). The website generates its copy from the same
`palettes.json`, with `D:\Wordpress Facet Plugin\Scripts\gen_tier_sets.py`.
This is the viewer's copy of that generator, so **no hex value is ever typed
by hand in either program** and the two cannot drift apart.

The distance tables are the point of the exercise. Two tiers that TOUCH must
be far apart *as that viewer sees them*, which means CIEDE2000 after a
color-blindness simulation - and the simulation lives in the research's
`tier_palettes.py`, on top of scikit-image. Rather than make the viewer
depend on scikit-image to recompute what is a fixed table of numbers, the
tables are computed here, once, and emitted as data. The viewer then needs
nothing but numpy, exactly as before.

Run this on the workstation that has the research tree. The generated file is
committed, so a machine without it can still build and run the viewer.
"""
from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RESEARCH = r"D:\Facetdiagrams.org\research\tier-colors"
SRC = os.path.join(RESEARCH, "palettes.json")
OUT = os.path.join(HERE, "tier_sets_data.py")

# Loyd's labels and order, 2026-11-11, as the website's dropdown shows them:
# the two normal-vision sets first, named "None (...)" because they correct
# for nothing.  (set id, key in palettes.json, which field, label)
ORDER = [
    ("vibrant", "normal", "optimized_alternative", "None (Vibrant)"),
    ("pastel", "normal", "colors", "None (Pastel)"),
    ("deuteranomaly", "deuteranomaly", "colors", "Deuteranomaly (Green-weak)"),
    ("protanomaly", "protanomaly", "colors", "Protanomaly (Red-weak)"),
    ("deuteranopia", "deuteranopia", "colors", "Deuteranopia (Green-blind)"),
    ("protanopia", "protanopia", "colors", "Protanopia (Red-blind)"),
    ("tritanomaly", "tritanomaly", "colors", "Tritanomaly (Blue-weak)"),
    ("tritanopia", "tritanopia", "colors", "Tritanopia (Blue-blind)"),
    ("achromatopsia", "achromatopsia", "colors",
     "Achromatopsia / Rod Monochromacy (Total color blindness)"),
    ("bcm", "bcm", "colors",
     "Blue Cone Monochromacy (Severe red-green blindness / partial monochromacy)"),
]

HEADER = '''\
"""GENERATED by scripts/gen_tier_sets.py - do not edit by hand.

The ten tier-color sets, from the tier-color research at
D:\\\\Facetdiagrams.org\\\\research\\\\tier-colors (palettes.json), the same source
the website generates src/viewer/tierSetsData.ts from.

Each entry:
    id      short name, what gets remembered between runs
    label   what the menu shows
    colors  the colors as DRAWN, in assignment order
    seen    the colors as that viewer SEES them (None for normal vision)
    flat    the two monochromacies: lightness is the only cue they have, so
            the stone is drawn without shading, which would spend it
    seenD   CIEDE2000 between every pair AS SEEN, from the research's own
            simulation, so the viewer assigns exactly as the research checked
"""

TIER_SETS_DATA = [
'''


def build():
    sys.path.insert(0, r"D:\Facetdiagrams.org\Scripts")
    import tier_assign as tas          # the research's own seen_distance

    sets = json.load(open(SRC, encoding="utf-8"))["sets"]["16"]
    out = [HEADER]
    for sid, src, field, label in ORDER:
        e = sets[src]
        colors = [c.lower() for c in e[field]]
        seen = ([c.lower() for c in e["seen_as"]]
                if field == "colors" and "seen_as" in e else None)
        # normal vision sees what is drawn, so its table is measured on the
        # colors themselves - which is what passing "normal" does
        D = tas.seen_distance(e[field], src if field == "colors" else "normal")
        out.append("    {\n")
        out.append("        %-9s %s,\n" % ('"id":', json.dumps(sid)))
        out.append("        %-9s %s,\n" % ('"label":', json.dumps(label)))
        out.append("        %-9s %s,\n" % ('"colors":', json.dumps(colors)))
        # json.dumps(None) is "null", which is not Python
        out.append("        %-9s %s,\n"
                   % ('"seen":', json.dumps(seen) if seen else "None"))
        out.append("        %-9s %s,\n"
                   % ('"flat":', bool(e.get("flat_shading_required"))))
        out.append('        "seenD": [\n')
        for row in D:
            out.append("            [%s],\n"
                       % ", ".join(repr(round(float(x), 9)) for x in row))
        out.append("        ],\n")
        out.append("    },\n")
    out.append("]\n")
    return "".join(out)


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if not os.path.exists(SRC):
        sys.exit("the research tree is not on this machine: %s\n"
                 "tier_sets_data.py is committed, so nothing needs "
                 "regenerating to build or run the viewer." % SRC)
    text = build()
    if "--check" in argv:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != text:
            sys.exit("tier_sets_data.py is out of date - run %s"
                     % os.path.basename(__file__))
        print("tier_sets_data.py matches %s" % SRC)
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print("%s (%d sets)" % (OUT, len(ORDER)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
